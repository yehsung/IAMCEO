export type ErrorCode = keyof typeof ERROR_CODES;

export function isErrorCode(value: unknown): value is ErrorCode {
  return typeof value === "string" && Object.prototype.hasOwnProperty.call(ERROR_CODES, value);
}

/** 코드의 대표 문장. 서버 응답은 자리마다 만든 실제 문장을 그대로 싣고, 이 함수는 표시 대체용이다. */
export function errorText(code: ErrorCode, lang: "ko" | "en" = "ko"): string {
  const entry: ErrorCodeText = ERROR_CODES[code];
  return lang === "en" ? entry.en ?? entry.ko : entry.ko;
}

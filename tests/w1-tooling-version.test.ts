import { expect, test } from "bun:test";
import { existsSync, readFileSync } from "node:fs";
import { join, resolve } from "node:path";
import pkg from "../package.json";

// package.json is the one source of the version. Every other place that repeats it, and every generated
// file that is committed, is compared here so a version bump or a project.yml edit cannot leave one behind.
const root = resolve(import.meta.dir, "..");
const text = (path: string) => readFileSync(join(root, path), "utf8");
const projectYml = text("native/project.yml");
const project = Bun.YAML.parse(projectYml) as { targets: Record<string, { info: { path: string; properties: Record<string, unknown> } }> };

test("version: package.json is a stable X.Y.Z version", () => {
  expect(pkg.version).toMatch(/^\d+\.\d+\.\d+$/);
});

test("version: every MARKETING_VERSION in native/project.yml equals package.json", () => {
  const versions = [...projectYml.matchAll(/^\s*MARKETING_VERSION:\s*'?([^'\s]+)'?\s*$/gm)].map(match => match[1]);
  expect(versions.length).toBeGreaterThan(0);
  // On failure: set every MARKETING_VERSION in native/project.yml to the package.json version.
  expect(versions).toEqual(versions.map(() => pkg.version));
});

test("version: the Homebrew cask template equals package.json", () => {
  const cask = text("packaging/homebrew/Casks/iamceo.rb").match(/^\s*version "([^"]+)"$/m)?.[1];
  // On failure: set version in packaging/homebrew/Casks/iamceo.rb to the package.json version.
  expect(cask).toBe(pkg.version);
});

test("version: the app bundles take their version from the build, not from a fourth copy", () => {
  // iPhone: the plist defers to build settings, and release-ios.ts passes the package.json version to xcodebuild.
  const ios = project.targets["IAMCEO-iOS"].info.properties;
  expect(ios.CFBundleShortVersionString).toBe("$(MARKETING_VERSION)");
  expect(ios.CFBundleVersion).toBe("$(CURRENT_PROJECT_VERSION)");
  expect(text("scripts/release-ios.ts")).toContain("`MARKETING_VERSION=${version}`");
  // Mac: build-native.ts writes the package.json version into the built bundle; release-mac.ts refuses a mismatch.
  expect(text("scripts/build-native.ts")).toContain("`Set :CFBundleShortVersionString ${pkg.version}`");
  expect(text("scripts/release-mac.ts")).toContain('throw new Error("Built app version differs from release version")');
});

test("project: the SwiftTerm version pinned for Xcode builds equals the one pinned for swift test", () => {
  // Tests run through Package.swift, the shipped apps through project.yml: a different pin would test one library and ship another.
  const xcode = (Bun.YAML.parse(projectYml) as { packages: { SwiftTerm: { exactVersion: string } } }).packages.SwiftTerm.exactVersion;
  const swiftpm = text("native/Package.swift").match(/SwiftTerm",\s*exact:\s*"([^"]+)"/)?.[1];
  expect(xcode).toMatch(/^\d+\.\d+\.\d+$/);
  expect(swiftpm).toBe(xcode);
});

test.skipIf(process.platform !== "darwin").each(["IAMCEO-iOS", "IAMCEO-macOS"])("project: the committed Info.plist of %s carries every property project.yml declares", name => {
  const target = project.targets[name];
  const file = join(root, "native", target.info.path);
  const converted = Bun.spawnSync(["/usr/bin/plutil", "-convert", "json", "-o", "-", file], { stdout: "pipe", stderr: "pipe" });
  expect(converted.exitCode, converted.stderr.toString()).toBe(0);
  const plist = JSON.parse(converted.stdout.toString()) as Record<string, unknown>;
  // The plist is generated by XcodeGen. On failure: run `xcodegen generate` in native/ and commit native/Configuration/*.plist.
  for (const [key, value] of Object.entries(target.info.properties)) expect(plist[key], `${target.info.path}: ${key}`).toEqual(value);
});

test("project: permission sentences shown by the system are Korean on both platforms", () => {
  for (const name of ["IAMCEO-iOS", "IAMCEO-macOS"]) {
    for (const [key, value] of Object.entries(project.targets[name].info.properties)) {
      if (key.endsWith("UsageDescription")) expect(String(value), `${name} ${key}`).toMatch(/[가-힣]/);
    }
  }
});

test("release tooling: no credential, personal path or contact detail is committed", () => {
  // The iPhone target's team ID is already in project.yml; the release tool and its guide must still take it from the environment.
  const team = projectYml.match(/DEVELOPMENT_TEAM:\s*'?([A-Z0-9]{10})'?/)![1];
  const files = ["scripts/release-ios.ts", "docs/releasing.md", "install.sh", "scripts/release-mac.ts"];
  for (const path of files) {
    expect(existsSync(join(root, path)), path).toBe(true);
    const content = text(path);
    expect(content, `${path}: absolute home path`).not.toMatch(/\/Users\/[A-Za-z0-9._-]+/);
    expect(content, `${path}: e-mail address`).not.toMatch(/[A-Za-z0-9._%+-]+@[A-Za-z0-9-]+\.[A-Za-z]{2,}/);
    expect(content, `${path}: key file name`).not.toMatch(/AuthKey_[A-Z0-9]{6,}/);
    expect(content, `${path}: issuer-shaped identifier`).not.toMatch(/\b[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\b/i);
    expect(content, `${path}: private key`).not.toContain("PRIVATE KEY");
    expect(content, `${path}: phone number`).not.toMatch(/(?:\+\d{1,3}[ -]?)?\b0?1\d[ -]\d{3,4}[ -]\d{4}\b/);
  }
  for (const path of ["scripts/release-ios.ts", "docs/releasing.md"]) expect(text(path), `${path}: team ID`).not.toContain(team);
});
